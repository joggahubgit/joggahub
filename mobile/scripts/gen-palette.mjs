// Generates tailwind.palette.js from the web's Tailwind v4 theme (OKLCH) so the
// app renders the exact same colours as the web. NativeWind runs Tailwind v3,
// whose default palette is slightly different.
// Usage: node scripts/gen-palette.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const here = path.dirname(fileURLToPath(import.meta.url));
const themeCss = readFileSync(path.resolve(here, '../../node_modules/tailwindcss/theme.css'), 'utf8');

function oklchToHex(L, C, H) {
  const h = (H * Math.PI) / 180;
  const a = C * Math.cos(h);
  const b = C * Math.sin(h);
  const l_ = L + 0.3963377774 * a + 0.2158037573 * b;
  const m_ = L - 0.1055613458 * a - 0.0638541728 * b;
  const s_ = L - 0.0894841775 * a - 1.291485548 * b;
  const [l, m, s] = [l_ ** 3, m_ ** 3, s_ ** 3];
  const lin = [
    4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s,
    -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s,
    -0.0041960863 * l - 0.7034186147 * m + 1.707614701 * s,
  ];
  const toSrgb = (x) => {
    const v = x <= 0.0031308 ? 12.92 * x : 1.055 * Math.pow(x, 1 / 2.4) - 0.055;
    return Math.round(Math.min(1, Math.max(0, v)) * 255); // clip to sRGB like an sRGB display
  };
  return '#' + lin.map(toSrgb).map((n) => n.toString(16).padStart(2, '0')).join('');
}

const palette = {};
const re = /--color-([a-z]+)-(\d+):\s*oklch\(([\d.]+)%\s+([\d.]+)\s+([\d.]+)\)/g;
for (const [, name, shade, L, C, H] of themeCss.matchAll(re)) {
  (palette[name] ??= {})[shade] = oklchToHex(Number(L) / 100, Number(C), Number(H));
}
palette.white = '#ffffff';
palette.black = '#000000';
palette.transparent = 'transparent';

writeFileSync(
  path.resolve(here, '../tailwind.palette.js'),
  `// Generated by scripts/gen-palette.mjs from the web's Tailwind v4 theme. Do not edit.\nmodule.exports = ${JSON.stringify(palette, null, 2)};\n`,
);
console.log('colours:', Object.keys(palette).length, 'violet-600 =', palette.violet['600']);
